"""Fit shift amount models on the whole mainnet trace and emit mainnet_shift_model.hpp.

For each of SHL, SHR, SAR (amounts <= 255):
- the histogram of shift amounts,
- the first-order Markov chain: for each amount, the counts of the amounts following it,
  keeping the most frequent ones covering ROW_MASS of the row's occurrences.

Usage: gen_shift_amount_model.py <trace_dir> <out.hpp>
"""
import glob
import os
import sys
from collections import Counter, defaultdict

ROW_MASS = 0.99
OPS = {0x1B: "shl", 0x1C: "shr", 0x1D: "sar"}

trace_dir, out_path = sys.argv[1], sys.argv[2]

seq = {name: [] for name in OPS.values()}
blocks = []
for path in sorted(glob.glob(os.path.join(trace_dir, "*.bin"))):
    blocks.append(int(os.path.basename(path)[:-4]))
    data = open(path, "rb").read()
    for i in range(0, len(data) - 64, 65):
        if not any(data[i + 2 : i + 33]):  # skip amounts > 255
            seq[OPS[data[i]]].append(data[i + 1])


def entries(counter):
    return "\n".join(
        "    " + " ".join(f"{{{a}, {c}}}," for a, c in row)
        for row in (lambda items: [items[i:i + 6] for i in range(0, len(items), 6)])(counter)
    )


with open(out_path, "w") as f:
    f.write(f"""// evmone: Fast Ethereum Virtual Machine implementation
// Copyright 2026 The evmone Authors.
// SPDX-License-Identifier: Apache-2.0
#pragma once

#include <cstdint>
#include <span>

/// Models of SHL, SHR and SAR shift amounts fitted on all shift instructions executed in
/// 200 mainnet blocks from the range {blocks[0]}..{blocks[-1]}. Generated by
/// mainnet_shifts/gen_shift_amount_model.py. Shift amounts greater than 255 are skipped.
namespace evmone::test::mainnet_shift_model
{{
/// A shift amount with its number of occurrences.
struct AmountCount
{{
    uint8_t amount;
    uint32_t count;
}};

/// The shift amount model.
struct Model
{{
    /// The numbers of occurrences of shift amounts.
    std::span<const AmountCount> histogram;

    /// The first-order Markov chain: transitions[row_offsets[a], row_offsets[a + 1]) are
    /// the numbers of occurrences of shift amounts directly following the shift amount a.
    /// Only the most frequent ones covering {ROW_MASS:.0%} of each row's occurrences are kept.
    std::span<const uint16_t, 257> row_offsets;
    std::span<const AmountCount> transitions;
}};

// clang-format off
""")
    for name, s in seq.items():
        hist = sorted(Counter(s).items(), key=lambda x: (-x[1], x[0]))
        rows = defaultdict(Counter)
        for a, b in zip(s, s[1:]):
            rows[a][b] += 1

        offsets, transitions = [0], []
        for a in range(256):
            row = sorted(rows[a].items(), key=lambda x: (-x[1], x[0]))
            total, acc = sum(c for _, c in row), 0
            for b, c in row:
                transitions.append((b, c))
                acc += c
                if acc >= ROW_MASS * total:
                    break
            offsets.append(len(transitions))

        f.write(f"\n/// {name.upper()}: {len(s)} shift amounts, {len(hist)} distinct, "
                f"{len(transitions)} transitions.\n")
        f.write(f"inline constexpr AmountCount {name}_histogram[] = {{\n{entries(hist)}\n}};\n")
        f.write(f"inline constexpr uint16_t {name}_row_offsets[] = {{\n")
        for i in range(0, len(offsets), 16):
            f.write("    " + ", ".join(map(str, offsets[i:i + 16])) + ",\n")
        f.write("};\n")
        f.write(f"inline constexpr AmountCount {name}_transitions[] = {{\n{entries(transitions)}\n}};\n")
        f.write(f"inline constexpr Model {name}{{{name}_histogram, {name}_row_offsets, "
                f"{name}_transitions}};\n")
        print(f"{name}: histogram={len(hist)} transitions={len(transitions)}")
    f.write("// clang-format on\n}  // namespace evmone::test::mainnet_shift_model\n")
print("wrote", out_path)
